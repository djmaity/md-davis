from __future__ import annotations

from math import ceil, floor, sqrt
from os import PathLike
from typing import TextIO

import numpy as np
from numpy.typing import NDArray


class CUBE:
    def __init__(self, fname: str | PathLike[str]) -> None:
        with open(fname, encoding="utf-8") as cube_file:
            next(cube_file)
            next(cube_file)

            tokens = cube_file.readline().split()
            self.natoms = int(tokens[0])
            self.origin = np.array([float(value) for value in tokens[1:4]])

            self.NX, self.X = self._parse_axis(cube_file.readline())
            self.NY, self.Y = self._parse_axis(cube_file.readline())
            self.NZ, self.Z = self._parse_axis(cube_file.readline())

            self.atoms = []
            for _ in range(self.natoms):
                tokens = cube_file.readline().split()
                self.atoms.append([tokens[0], tokens[2], tokens[3], tokens[4]])

            values = np.fromstring(cube_file.read(), sep=" ")

        expected_values = self.NX * self.NY * self.NZ
        if values.size != expected_values:
            raise ValueError(f"Expected {expected_values} volumetric values, found {values.size}")
        self.data = values.reshape((self.NX, self.NY, self.NZ))

    @staticmethod
    def _parse_axis(line: str) -> tuple[int, NDArray]:
        tokens = line.split()
        return int(tokens[0]), np.array([float(value) for value in tokens[1:4]])

    def dump(self, f: TextIO) -> None:
        # output Gaussian cube into file descriptor "f".
        # Usage pattern: f=open('filename.cube'); cube.dump(f); f.close()
        print("CUBE file\ngenerated by piton _at_ erg.biophys.msu.ru", file=f)
        print(f"{self.natoms:4d} {self.origin[0]:.6f} {self.origin[1]:.6f} {self.origin[2]:.6f}", file=f)
        print(f"{self.NX:4d} {self.X[0]:.6f} {self.X[1]:.6f} {self.X[2]:.6f}", file=f)
        print(f"{self.NY:4d} {self.Y[0]:.6f} {self.Y[1]:.6f} {self.Y[2]:.6f}", file=f)
        print(f"{self.NZ:4d} {self.Z[0]:.6f} {self.Z[1]:.6f} {self.Z[2]:.6f}", file=f)
        for atom in self.atoms:
            print(f"{atom[0]} 0 {atom[1]} {atom[2]} {atom[3]}", file=f)
        for ix in range(self.NX):
            for iy in range(self.NY):
                for iz in range(self.NZ):
                    print(f"{self.data[ix, iy, iz]:.5e}", end=" ", file=f)
                    if iz % 6 == 5:
                        print("", file=f)
                print("", file=f)

    def mask_sphere(self, R: float, Cx: float, Cy: float, Cz: float) -> NDArray:
        # produce spheric volume mask with radius R and center @ [Cx,Cy,Cz]
        # can be used for integration over spherical part of the volume
        m = 0 * self.data
        for ix in range(int(ceil((Cx - R) / self.X[0])), int(floor((Cx + R) / self.X[0]))):
            ryz = sqrt(R**2 - (ix * self.X[0] - Cx) ** 2)
            for iy in range(int(ceil((Cy - ryz) / self.Y[1])), int(floor((Cy + ryz) / self.Y[1]))):
                rz = sqrt(ryz**2 - (iy * self.Y[1] - Cy) ** 2)
                for iz in range(int(ceil((Cz - rz) / self.Z[2])), int(floor((Cz + rz) / self.Z[2]))):
                    m[ix, iy, iz] = 1
        return m


def bohr2angs(value: float) -> float:
    return round(0.529177 * value, 6)


bohr2angstrom = np.vectorize(bohr2angs)


def cube2angstrom(data: CUBE) -> tuple[NDArray, float, float, float]:
    """Correct way of converting Bohr unit in CUBE format to Angstrom"""
    if data.X[0] > 0:
        X = bohr2angstrom(data.X)
        Y = bohr2angstrom(data.Y)
        Z = bohr2angstrom(data.Z)
        origin = bohr2angstrom(data.origin)
    else:
        X = data.X
        Y = data.Y
        Z = data.Z
        origin = data.origin

    x_step = np.linalg.norm(X)
    y_step = np.linalg.norm(Y)
    z_step = np.linalg.norm(Z)
    return origin, x_step, y_step, z_step
