#!/usr/bin/env python3

from __future__ import annotations

from collections.abc import Mapping, Sequence

from md_davis.analysis.landscape.landscape import AxisLimits, Landscape
from md_davis.io.config import parse_literal
from md_davis.io.xvg import Xvg


def landscape_xvg(
    x: Sequence[str],
    y: Sequence[str],
    name: Sequence[str],
    label: Sequence[str],
    common: bool = False,
    temperature: float | None = None,
    output: str = "landscapes.html",
    save: str | None = None,
    title: str | None = None,
    shape: tuple[int, int] = (100, 100),
    begin: int = 0,
    end: int | None = None,
    limits: AxisLimits | str | None = None,
    orthographic: bool = False,
    layout: Sequence[int] | str | None = None,
    width: int | None = None,
    height: int | None = None,
    font: str | None = None,
    font_size: int | None = None,
    dtick: Mapping[str, float] | str | None = None,
    axis_labels: Mapping[str, str] | str | None = None,
) -> None:
    """Plot free energy landscapes from .xvg files generated by GROMACS"""

    if limits is not None:
        limits = parse_literal(limits, dict)

    input_data = {}
    landscapes = []
    for x_file, y_file, landscape_name, landscape_label in zip(x, y, name, label, strict=True):
        data1 = Xvg(x_file)
        data2 = Xvg(y_file)

        time = data1.data[begin:end, 0]
        x_data = data1.data[begin:end, 1]
        y_data = data2.data[begin:end, 1]

        if len(time) < 1 or len(x_data) < 1 or len(y_data) < 1:
            raise ValueError("Invalid value for begin or end")

        if common:
            input_data[landscape_name] = [time, x_data, y_data, landscape_label]
        else:
            print(f"Generating Landscape for {landscape_name}")
            landscape = Landscape.landscape(
                name=landscape_name,
                time=time,
                x_data=x_data,
                y_data=y_data,
                shape=shape,
                label=landscape_label,
                temperature=temperature,
                limits=limits,
            )
            landscapes.append(landscape)

    if common and len(input_data) > 0:
        landscapes = Landscape.common_landscapes(
            data=input_data,
            shape=shape,
            temperature=temperature,
            limits=limits,
        )

    if save:
        for ls in landscapes:
            ls.save(filename=save, name=ls.name, xlabel="RMSD", ylabel="Radius of Gyration")

    Landscape.plot_landscapes(
        landscapes=landscapes,
        title=title,
        filename=output,
        axis_labels=axis_labels,
        width=width,
        height=height,
        othrographic=orthographic,
        dtick=parse_literal(dtick, dict),
        layout=parse_literal(layout, (list, tuple)),
        font_family=font,
        font_size=font_size,
    )


def main(
    x: Sequence[str],
    y: Sequence[str],
    name: Sequence[str],
    label: Sequence[str],
    common: bool = False,
    temperature: float | None = None,
    output: str = "landscapes.html",
    save: str | None = None,
    title: str | None = None,
    shape: tuple[int, int] = (100, 100),
    begin: int = 0,
    end: int | None = None,
    limits: AxisLimits | str | None = None,
    orthographic: bool = False,
    layout: Sequence[int] | str | None = None,
    width: int | None = None,
    height: int | None = None,
    font: str | None = None,
    font_size: int | None = None,
    dtick: Mapping[str, float] | str | None = None,
    axis_labels: Mapping[str, str] | str | None = None,
) -> None:
    """Create and plot landscapes from XVG data."""
    landscape_xvg(
        x=x,
        y=y,
        name=name,
        label=label,
        common=common,
        temperature=temperature,
        output=output,
        save=save,
        title=title,
        shape=shape,
        begin=begin,
        end=end,
        limits=limits,
        orthographic=orthographic,
        layout=layout,
        width=width,
        height=height,
        font=font,
        font_size=font_size,
        dtick=dtick,
        axis_labels=axis_labels,
    )


if __name__ == "__main__":
    import sys

    from md_davis.cli import main as cli_main

    raise SystemExit(cli_main(["landscape_xvg", *sys.argv[1:]]))
