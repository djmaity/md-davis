def existing_path(value: str) -> str:
    """Return *value* when it exists, otherwise report an argparse error."""
    if not Path(value).exists():
        raise argparse.ArgumentTypeError(f"path does not exist: {value}")
    return value


def add_boolean_pair(
    parser: argparse.ArgumentParser,
    positive: str | tuple[str, ...],
    negative: str | tuple[str, ...],
    *,
    dest: str,
    default: bool,
    help: str,
) -> None:
    """Add mutually exclusive positive and negative boolean flags."""
    positive_flags = (positive,) if isinstance(positive, str) else positive
    negative_flags = (negative,) if isinstance(negative, str) else negative
    group = parser.add_mutually_exclusive_group()
    group.add_argument(*positive_flags, dest=dest, action="store_true", help=help)
    alternative = negative_flags[0].removeprefix("--").replace("-", " ")
    group.add_argument(*negative_flags, dest=dest, action="store_false", help=f"Use {alternative} mode")
    parser.set_defaults(**{dest: default})


def add_command(
    subparsers: argparse._SubParsersAction[argparse.ArgumentParser],
    name: str,
    handler: Handler,
    help: str,
) -> argparse.ArgumentParser:
    parser = subparsers.add_parser(name, help=help, description=help)
    parser.set_defaults(_handler=handler)
    return parser


